// Writes build/.htaccess so Apache serves the site's own 404 page. The path
// has to be absolute, so it is generated from the base URL rather than kept
// in static/.
function apacheHtaccess() {
  return {
    name: 'apache-htaccess',
    async postBuild({ outDir, baseUrl }) {
      fs.writeFileSync(
        `${outDir}/.htaccess`,
        [
          '# Generated by docusaurus.config.js for Apache httpd.',
          `ErrorDocument 404 ${baseUrl}404.html`,
          '',
        ].join('\n'),
      );
    },
  };
}

function hasGitBookAssets() {
  const dir = new URL('./content/.gitbook/assets/', import.meta.url);
  return fs.existsSync(dir) && fs.readdirSync(dir).some((f) => !f.startsWith('.'));
}

